// Helper: Get verified outlets for a country
export function getOutletsForCountry(countryCode: string): NewsOutlet[] {
  if (!countryCode) return [];
  const code = countryCode.toUpperCase();
  return NEWS_OUTLETS.filter((o) => o.countryCode.toUpperCase() === code);
}

// Helper: Look up outlet by domain or name
export function findOutletByDomainOrName(domainOrName: string): NewsOutlet | undefined {
  if (!domainOrName) return undefined;
  const q = domainOrName.toLowerCase().trim();

  // 1. Try domain match
  for (const o of NEWS_OUTLETS) {
    if (o.domain && (q === o.domain || q.endsWith('.' + o.domain) || o.domain.includes(q))) {
      return o;
    }
    if (o.domains && o.domains.some((d) => q === d || q.endsWith('.' + d) || d.includes(q))) {
      return o;
    }
  }

  // 2. Try exact or partial name match
  return NEWS_OUTLETS.find(
    (o) =>
      o.name.toLowerCase() === q ||
      o.name.toLowerCase().includes(q) ||
      q.includes(o.name.toLowerCase())
  );
}

// Helper: Check if an outlet is verified local to a country
export function isOutletLocalToCountry(publisher: string, countryCode: string, link?: string): boolean {
  if (!countryCode) return false;
  const upperCode = countryCode.toUpperCase();

  // Link hostname lookup
  if (link) {
    try {
      const url = new URL(link);
      const host = url.hostname.toLowerCase();
      const matched = findOutletByDomainOrName(host);
      if (matched) {
        return matched.countryCode.toUpperCase() === upperCode;
      }
    } catch {
      // not a valid URL
    }
  }

  // Publisher name lookup
  if (publisher) {
    const matched = findOutletByDomainOrName(publisher);
    if (matched) {
      return matched.countryCode.toUpperCase() === upperCode;
    }
  }

  return false;
}

export function searchOutlets(query: string): NewsOutlet[] {
  const q = query.toLowerCase().trim();
  if (!q) return NEWS_OUTLETS;
  return NEWS_OUTLETS.filter(
    (o) =>
      o.name.toLowerCase().includes(q) ||
      o.countryName.toLowerCase().includes(q) ||
      o.category.toLowerCase().includes(q) ||
      o.language.toLowerCase().includes(q) ||
      (o.domain && o.domain.toLowerCase().includes(q))
  );
}

export interface OutletMetadataResult {
  publisherId?: string;
  ownership: OwnershipType;
  ownershipCategory?: OwnershipCategory;
  editorialIndependence: EditorialIndependence;
  politicalPerspective: PoliticalPerspective;
  factualReliability: FactualReliability;
  publisherCountry?: string;
  publisherDomain?: string;
  assessmentProvider?: string;
  assessmentUrl?: string;
  isEvaluated: boolean;
  isLocalPublisher?: boolean;
}

export function getOutletMetadata(publisher: string, link?: string): OutletMetadataResult {
  let match: NewsOutlet | undefined = undefined;

  if (link) {
    try {
      const url = new URL(link);
      match = findOutletByDomainOrName(url.hostname.toLowerCase());
    } catch {
      // ignore
    }
  }

  if (!match && publisher) {
    match = findOutletByDomainOrName(publisher);
  }

  if (match) {
    return {
      publisherId: match.id,
      ownership: match.ownership,
      ownershipCategory: match.ownershipCategory,
      editorialIndependence: match.editorialIndependence,
      politicalPerspective: match.politicalPerspective,
      factualReliability: match.factualReliability,
      publisherCountry: match.countryCode,
      publisherDomain: match.domain,
      assessmentProvider: match.assessmentProvider,
      assessmentUrl: match.assessmentUrl,
      isEvaluated: true,
      isLocalPublisher: match.isLocalPublisher,
    };
  }

  return {
    ownership: 'Unknown',
    ownershipCategory: 'unknown',
    editorialIndependence: 'Unknown',
    politicalPerspective: 'Not rated',
    factualReliability: 'Not rated',
    publisherCountry: undefined,
    publisherDomain: undefined,
    assessmentProvider: undefined,
    assessmentUrl: undefined,
    isEvaluated: false,
    isLocalPublisher: false,
  };
}
